"""Generates rust/crates/af-science/src/catalog_table.rs from the C++
science/ScienceCatalog.cpp initializer (the tool and parameter definitions)."""
import re
import sys

src = open(sys.argv[1] if len(sys.argv) > 1 else "src/science/ScienceCatalog.cpp", encoding="utf-8").read()
start = src.index("tools = {") + len("tools = ")
body = src[start:src.index("};", start) + 1]

token_re = re.compile(r'"((?:[^"\\]|\\.)*)"|([{}])|(,)|([A-Za-z_][A-Za-z0-9_:]*)|(\s+)|(//[^\n]*)')
pos = 0
tokens = []
while pos < len(body):
    m = token_re.match(body, pos)
    if not m:
        raise SystemExit(f"unexpected text at {pos}: {body[pos:pos+40]!r}")
    pos = m.end()
    if m.group(1) is not None:
        if tokens and tokens[-1][0] == "str":
            tokens[-1] = ("str", tokens[-1][1] + m.group(1))
        else:
            tokens.append(("str", m.group(1)))
    elif m.group(2):
        tokens.append((m.group(2), None))
    elif m.group(3):
        tokens.append((",", None))
    elif m.group(4):
        tokens.append(("id", m.group(4)))


def parse(i):
    assert tokens[i][0] == "{"
    i += 1
    items = []
    while tokens[i][0] != "}":
        if tokens[i][0] == ",":
            i += 1
            continue
        if tokens[i][0] == "{":
            item, i = parse(i)
        else:
            item = tokens[i]
            i += 1
        items.append(item)
    return items, i + 1


tools, _ = parse(0)


def rs(s):
    # C++ escapes used in the catalog (\n, \", \\) are valid Rust escapes.
    return '"' + s + '"'


out = ["// Generated by rust/tools/gen_catalog.py from src/science/ScienceCatalog.cpp. Do not edit.",
       "use super::catalog::{ParameterDef as P, ToolDef, ToolView};", "",
       "pub static TOOLS: &[ToolDef] = &["]
for tool in tools:
    if len(tool) != 6: raise SystemExit(repr(tool)[:600])
    id_, title, help_, category, params, view = tool
    out.append("    ToolDef {")
    out.append(f"        id: {rs(id_[1])},")
    out.append(f"        title: {rs(title[1])},")
    out.append(f"        help: {rs(help_[1])},")
    out.append(f"        category: {rs(category[1])},")
    out.append("        parameters: &[")
    for p in params:
        name, label, value, kind, required = p
        out.append(f"            P {{ name: {rs(name[1])}, label: {rs(label[1])}, value: {rs(value[1])}, kind: {rs(kind[1])}, required: {required[1]} }},")
    out.append("        ],")
    out.append(f"        view: ToolView::{view[1].split('::')[-1]},")
    out.append("    },")
out.append("];")
dest = sys.argv[2] if len(sys.argv) > 2 else "rust/crates/af-science/src/catalog_table.rs"
open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(tools), "tools")
