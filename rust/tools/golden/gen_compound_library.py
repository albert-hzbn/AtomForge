"""Generates crates/af-chemistry/src/compound_library.rs from the compound
library table of src/chemistry/Builders.cpp (compoundLibrary()). Run from the
repository root: python rust/tools/golden/gen_compound_library.py"""
import re

src = open("src/chemistry/Builders.cpp", encoding="utf-8").read()
start = src.index("static const std::vector<NamedCompound> library = {")
end = src.index("};", start)
body = src[start:end]
string = r'"(?:[^"\\]|\\.)*"'
entries = re.findall(r"\{(%s), (%s), (%s)\}" % (string, string, string), body)
out = [
    "//! The named-compound library of the C++ chemistry/Builders (generated by",
    "//! rust/tools/golden/gen_compound_library.py; do not edit).",
    "",
    "use crate::builders::NamedCompound;",
    "",
    "pub(crate) const COMPOUNDS: &[NamedCompound] = &[",
]
for name, category, smiles in entries:
    out.append("    NamedCompound { name: %s, category: %s, smiles: %s }," % (name, category, smiles))
out.append("];")
with open("rust/crates/af-chemistry/src/compound_library.rs", "w", newline="\n", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("%d compounds" % len(entries))
