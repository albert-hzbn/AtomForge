template <std::size_t N>
std::vector<glm::vec3> overlay(const float (&values)[N][3])
{
    std::vector<glm::vec3> colours = makeDefaultElementColors();
    for (std::size_t i = 0; i < N && i + 1 < colours.size(); ++i)
        colours[i + 1] = glm::vec3(values[i][0], values[i][1], values[i][2]);
    return colours;
}
