namespace atomforge::display
{
const std::vector<ColourScheme>& colourSchemes()
{
    static const std::vector<ColourScheme> all = {
        {"AtomForge", "The built-in CPK-style colours."},
        {"Jmol", "The colours of Jmol, also used by ASE."},
        {"RasMol CPK", "The classic RasMol CPK colours: a few saturated colours shared by element families."},
        {"Greyscale", "Grey levels of the AtomForge colours' brightness, for print in black and white."},
    };
    return all;
}

std::vector<glm::vec3> schemeColours(int scheme)
{
    switch (scheme) {
    case 1: return overlay(kJmol);
    case 2: return overlay(kRasmol);
    case 3: {
        std::vector<glm::vec3> colours = makeDefaultElementColors();
        for (glm::vec3& c : colours) {
            // Relative luminance, spread to 0.15-0.95 so no element is black or white.
            const float y = 0.2126f * c.r + 0.7152f * c.g + 0.0722f * c.b;
            c = glm::vec3(0.15f + 0.8f * y);
        }
        return colours;
    }
    default: return makeDefaultElementColors();
    }
}

int matchingScheme(const std::vector<glm::vec3>& colours)
{
    for (int i = 0; i < static_cast<int>(colourSchemes().size()); ++i)
        if (schemeColours(i) == colours) return i;
    return -1;
}
}  // namespace atomforge::display
