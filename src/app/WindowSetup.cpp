    static const std::array<const char*, 7> kM = {"#   #", "## ##", "# # #", "#   #", "#   #", "#   #", "#   #"};
    static const std::array<const char*, 7> kF = {"#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#    "};
    static const std::array<const char*, 7> kR = {"#### ", "#   #", "#   #", "#### ", "# #  ", "#  # ", "#   #"};
    static const std::array<const char*, 7> kG = {" ### ", "#   #", "#    ", "# ###", "#   #", "#   #", " ### "};
    static const std::array<const char*, 7> kE = {"#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#####"};

